/**
 * AI Match Analysis Generation
 *
 * Env vars:
 *   ANTHROPIC_API_KEY – Claude API key (optional)
 *   AI_MOCK_MODE      – "true" to use mock analysis
 *
 * Generates match previews and recaps from structured data only.
 * Claude is asked to return a strict JSON object — never free-form text.
 */

import type { Fixture, MatchDetail, H2HData, TeamStatistics, FixturePlayerStats } from "./football/types";

export type AnalysisLocale = "en" | "ko";

export interface AnalysisPrediction {
  outcome: "home" | "away" | "draw";
  label: string;
  confidence: number; // 0–100
}

export interface AnalysisTip {
  label: string;
  labelKo: string;
}

export interface AnalysisKeyFactor {
  icon: string;
  label: string;
  labelKo: string;
  value: string;
  valueKo: string;
}

export interface MatchAnalysis {
  id: string;
  fixtureId: number;
  type: "preview" | "recap";
  locale: AnalysisLocale;
  title: string;
  slug: string;
  summary: string;
  insight: string;
  prediction?: AnalysisPrediction;
  keyFactors?: AnalysisKeyFactor[];
  tips: AnalysisTip[];
  aiModel: string;
  generatedAt: string;
  disclaimer: string;
  isAiGenerated: boolean;
}

/** Optional enrichment data from API-Football endpoints */
export interface AnalysisEnrichmentData {
  h2h?: H2HData;
  homeStats?: TeamStatistics | null;
  awayStats?: TeamStatistics | null;
  /** Per-player fixture stats — used for MOM auto-selection in recaps */
  fixturePlayers?: FixturePlayerStats[];
}

export interface AnalysisGenerateInput {
  fixture: Fixture | MatchDetail;
  type: "preview" | "recap";
  locale?: AnalysisLocale;
  enrichment?: AnalysisEnrichmentData;
}

export const isAiMockMode =
  process.env.AI_MOCK_MODE === "true" || !process.env.ANTHROPIC_API_KEY;

function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

/** Stable, human-readable slug that avoids fixture IDs and locale noise.
 *  Format: {home}-vs-{away}-{YYYY-MM-DD}-{type}
 *  e.g.  arsenal-vs-bournemouth-2026-03-23-preview
 */
export function buildSlug(
  home: string,
  away: string,
  date: string,        // ISO date string
  type: "preview" | "recap"
): string {
  const day = date.split("T")[0] ?? date; // "2026-03-23"
  return `${slugify(home)}-vs-${slugify(away)}-${day}-${type}`;
}

